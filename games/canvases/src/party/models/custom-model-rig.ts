import * as THREE from 'three';
import { GLTFLoader } from 'three/examples/jsm/loaders/GLTFLoader.js';
import type { CharacterRig, Pose } from '../characters';
import { inspectGlb } from './validate';
import {seatedPose} from './seated';
import {wavePose} from './wave';
import {attachAnimatedHead,isSwappedHead}from'../costumes/seasonal-heads';
import {attachModelExtras}from'../costumes/head-frame';
import { MODEL_LIMITS, type ImportedModel, type ModelReport } from './types';
import { sharedModelBytes } from './model-bytes';

/** Fetched models are rechecked before parsing; no loader may fetch a second
 * URL from a user model. Embedded image blob URLs are generated by Three. */
export async function loadCustomModel(model: ImportedModel, signal?: AbortSignal, head: string | null = null, extras = false): Promise<CharacterRig> {
  if (!model.report.playable) throw new Error('This model needs a rig, idle clip and locomotion clip before it can be played.');
  return parseCustomModel(await sharedModelBytes(model.url, fetchModelBytes, signal), model.report, head, extras);
}

/** Shared by the library preview and the gameplay loader. */
export async function fetchModelBytes(url: string, signal?: AbortSignal): Promise<ArrayBuffer> {
  const response = await fetch(url, {signal, credentials: 'omit'});
  if (!response.ok) throw new Error('This model is no longer available.');
  const size = Number(response.headers.get('Content-Length'));
  if (size > MODEL_LIMITS.bytes) throw new Error('The model exceeds the download limit.');
  const reader = response.body?.getReader();
  if (!reader) throw new Error('The model download could not be read.');
  const chunks: Uint8Array[] = [];
  let length = 0;
  try {
    for (;;) {
      const {done, value} = await reader.read();
      if (done) break;
      length += value.byteLength;
      if (length > MODEL_LIMITS.bytes) { await reader.cancel(); throw new Error('The model exceeds the download limit.'); }
      chunks.push(value);
    }
  } finally { reader.releaseLock(); }
  const bytes = new Uint8Array(length);
  let offset = 0;
  for (const chunk of chunks) { bytes.set(chunk, offset); offset += chunk.length; }
  if (signal?.aborted) throw new DOMException('Aborted', 'AbortError');
  return bytes.buffer;
}

/** Preview accepts static GLBs too. Gameplay callers use loadCustomModel,
 * which also requires the API's authoritative playable flag. */
export async function parseCustomModel(data: ArrayBuffer, expected?: ModelReport, head: string | null = null, extras = false): Promise<CharacterRig> {
  const report = inspectGlb(data, expected?.clip_map);
  const manager = new THREE.LoadingManager();
  manager.setURLModifier((url) => {
    if (url.startsWith('blob:')) return url;
    throw new Error('This model tried to load an external resource.');
  });
  const gltf = await new GLTFLoader(manager).parseAsync(data, '');
  const root = gltf.scene;
  root.updateMatrixWorld(true);
  const box = new THREE.Box3().setFromObject(root);
  const dimensions = box.getSize(new THREE.Vector3());
  if (box.isEmpty() || ![dimensions.x, dimensions.y, dimensions.z].every(Number.isFinite) || dimensions.y <= 0.00001) {
    disposeObject(root);
    throw new Error('The model has no visible finite geometry.');
  }
  const height = 1.8;
  const scale = Math.min(height / dimensions.y, 2.2 / Math.max(dimensions.x, dimensions.z));
  const normalized = new THREE.Group();
  normalized.add(root);
  root.position.sub(new THREE.Vector3((box.min.x + box.max.x) / 2, box.min.y, (box.min.z + box.max.z) / 2));
  normalized.scale.setScalar(scale);
  const group = new THREE.Group();
  group.add(normalized);
  root.traverse((object) => {
    if ((object as THREE.Mesh).isMesh) { object.castShadow = true; object.receiveShadow = true; }
  });
  const mixer = new THREE.AnimationMixer(root);
  const actions = new Map<string, THREE.AnimationAction>();
  for (const source of gltf.animations) {
    // Keep locomotion in place: the game server moves the player's wrapper.
    // Preserve hip bob and all other bone animation, but remove horizontal
    // root motion from root-node/root-bone position tracks.
    const clip = source.clone();
    for (const track of clip.tracks) {
      if (!track.name.endsWith('.position')) continue;
      const name = track.name.slice(0, -'.position'.length);
      const node = root.getObjectByName(name);
      if (!node || !(node.parent === root || ((node as THREE.Bone).isBone && !(node.parent as THREE.Bone)?.isBone))) continue;
      const cubic = !!(track as THREE.KeyframeTrack & {createInterpolant?: {isInterpolantFactoryMethodGLTFCubicSpline?: boolean}}).createInterpolant?.isInterpolantFactoryMethodGLTFCubicSpline;
      const stride = cubic ? 9 : 3;
      const first = cubic ? 3 : 0;
      const x = track.values[first], z = track.values[first + 2];
      for (let i = 0; i < track.values.length; i += stride) {
        track.values[i + first] = x; track.values[i + first + 2] = z;
        if (cubic) { track.values[i] = track.values[i+2] = track.values[i+6] = track.values[i+8] = 0; }
      }
    }
    actions.set(clip.name, mixer.clipAction(clip));
  }
  const swapped=head&&isSwappedHead(head)?head:null;
  const headSwap=swapped?attachAnimatedHead(group,root,swapped):{update(){},dispose(){},ready:Promise.resolve()};
  const attachments=extras?attachModelExtras(group,root,swapped):null;
  const seated=seatedPose(root);
  const wave=wavePose(root);
  const sittingClip=[...actions.keys()].find(name=>/(?:^|[^a-z])(sit|sitting|sitdown|drive|driving)(?:$|[^a-z])/i.test(name))??null;
  let action: THREE.AnimationAction | null = null;
  let last: number | null = null;
  let disposed = false;
  const animate = (pose: Pose, time: number, speed: number, waveFor = 3) => {
    if (disposed) return;
    seated.restore();wave.restore();
    if(pose!=='wave')wave.reset();
    const sit=pose==='sit'?(report.clip_map.sit||sittingClip):null;
    // Uploaded models have no controller clip; they keep their idle while playing.
    const clip = sit || (pose === 'play' ? null : report.clip_map[pose]) || report.clip_map.idle;
    const next = clip ? actions.get(clip) ?? null : null;
    if (next !== action) {
      action?.fadeOut(0.15);
      if(next && sit){next.setLoop(THREE.LoopOnce,1);next.clampWhenFinished=true;}
      next?.reset();
      // The first clip shows at once; a fade from nothing would leave a still frame in its bind pose.
      if(action)next?.fadeIn(0.15);
      next?.play();
      action = next;
    }
    if (action) action.timeScale = pose === 'ride' ? THREE.MathUtils.clamp(Math.abs(speed) / 4, 0.65, 2) : 1;
    const dt = last === null ? 0 : THREE.MathUtils.clamp(time - last, 0, 0.1);
    last = time;
    mixer.update(dt);
    if(pose==='sit' && !sit)seated.apply();
    if(pose==='wave' && !report.clip_map.wave)wave.apply(time, waveFor);
    headSwap.update();attachments?.update();
  };
  animate('idle', 0, 0);
  return {
    group, animate, ready:headSwap.ready, attachments:attachments??undefined,
    dispose: () => {
      if (disposed) return;
      disposed = true;
      headSwap.dispose();attachments?.dispose();
      mixer.stopAllAction();
      mixer.uncacheRoot(root);
      disposeObject(root);
      group.removeFromParent();
    },
  };
}

function disposeObject(root: THREE.Object3D) {
  const geometries = new Set<THREE.BufferGeometry>();
  const materials = new Set<THREE.Material>();
  const textures = new Set<THREE.Texture>();
  const skeletons = new Set<THREE.Skeleton>();
  root.traverse((object) => {
    const mesh = object as THREE.Mesh;
    if (!mesh.isMesh) return;
    geometries.add(mesh.geometry);
    for (const material of Array.isArray(mesh.material) ? mesh.material : [mesh.material]) {
      materials.add(material);
      for (const value of Object.values(material)) if (value instanceof THREE.Texture) textures.add(value);
    }
    if ((object as THREE.SkinnedMesh).isSkinnedMesh) skeletons.add((object as THREE.SkinnedMesh).skeleton);
  });
  for (const texture of textures) { const image = texture.source?.data as {close?: () => void} | undefined; if (typeof image?.close === 'function') image.close(); texture.dispose(); }
  for (const material of materials) material.dispose();
  for (const geometry of geometries) geometry.dispose();
  for (const skeleton of skeletons) skeleton.dispose();
}
